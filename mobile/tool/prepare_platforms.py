#!/usr/bin/env python3
"""Creates and configures the android/ and ios/ folders for the TVV app.

Why this exists: the repository only keeps the Dart code. Flutter's own project files (android/, ios/) are generated
by `flutter create` with the SAME Flutter version that builds the app, which avoids version-drift build failures.
This script generates them in a temporary folder, copies them in, then applies the few changes the app needs:

  Android  - INTERNET permission (missing from release builds by default!), app name, no cloud backup of the secure
             token store, https-only traffic, "open link" visibility, release signing from key.properties.
  iOS      - display name, no export-compliance prompt for TestFlight.

Usage (from the `mobile/` folder):
  python3 tool/prepare_platforms.py --app-id com.tvv.school --app-name "TVV School"
Test mode (no Flutter needed): --scaffold-from <folder containing android/ and ios/>
Safe to run more than once.
"""
import argparse
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parent.parent


def fail(msg: str) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def scaffold(app_id: str, dest: Path) -> None:
    org, _, project = app_id.rpartition(".")
    if not org or not project.isidentifier():
        fail("--app-id must look like com.example.name (the last part: letters, digits, underscore)")
    kotlin_keywords = {"in", "is", "as", "do", "if", "fun", "val", "var", "for", "try", "when", "while", "object", "class", "package", "return", "super", "this", "throw", "typealias", "interface", "typeof", "null", "true", "false", "break", "continue", "else"}
    bad = [part for part in app_id.split(".") if part in kotlin_keywords]
    if bad:
        fail(f"--app-id contains the Kotlin keyword '{bad[0]}' (for example 'in.' cannot start an id); choose e.g. com.tvv.school")
    cmd = ["flutter", "create", "--no-pub", "--platforms", "android,ios", "--org", org, "--project-name", project, str(dest)]
    print("+", " ".join(cmd))
    subprocess.run(cmd, check=True)


def patch_manifest(path: Path, app_name: str) -> None:
    s = path.read_text(encoding="utf-8")
    if 'android.permission.INTERNET' not in s:
        s = re.sub(r"(<manifest[^>]*>)", r'\1\n    <uses-permission android:name="android.permission.INTERNET" />', s, count=1)
    s = re.sub(r'android:label="[^"]*"', "android:label=" + quoteattr(app_name), s, count=1)
    if "android:allowBackup" not in s:
        s = s.replace("<application", '<application\n        android:allowBackup="false"\n        android:usesCleartextTraffic="false"', 1)
    if 'android:scheme="https"' not in s:
        queries = '''        <intent>
            <action android:name="android.intent.action.VIEW"/>
            <data android:scheme="https"/>
        </intent>
        <intent>
            <action android:name="android.intent.action.VIEW"/>
            <data android:scheme="http"/>
        </intent>
'''
        if "</queries>" in s:
            s = s.replace("</queries>", queries + "    </queries>", 1)
        else:
            s = s.replace("</manifest>", "    <queries>\n" + queries + "    </queries>\n</manifest>", 1)
    path.write_text(s, encoding="utf-8")


# Gradle's Kotlin DSL only allows imports before the `plugins {}` block, so imports go on top and the code below it.
KEYSTORE_IMPORTS = """import java.io.FileInputStream
import java.util.Properties

"""

KEYSTORE_LOAD = """// Release signing: reads android/key.properties (written by the CI workflow from GitHub secrets).
// Without that file the release build falls back to the debug key so test APKs still install.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    FileInputStream(keystorePropertiesFile).use { keystoreProperties.load(it) }
}

"""

SIGNING_BLOCK = '''    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
            }
        }
    }

'''


def patch_gradle(path: Path) -> None:
    s = path.read_text(encoding="utf-8")
    # flutter_secure_storage (encrypted preferences) needs Android 6.0 (API 23) or newer.
    s2 = re.sub(r"minSdk\s*=\s*flutter\.minSdkVersion", "minSdk = maxOf(23, flutter.minSdkVersion)", s)
    if s2 != s:
        s = s2
        path.write_text(s, encoding="utf-8")
    if "keystoreProperties" in s:
        return  # already patched
    if path.suffix != ".kts":
        fail(f"{path.name}: expected the Kotlin DSL file generated by Flutter 3.29+; got a different template")
    if "buildTypes {" not in s or "signingConfigs.getByName(\"debug\")" not in s:
        fail("android/app/build.gradle.kts has an unexpected layout; update tool/prepare_platforms.py for this Flutter version")
    if "\nandroid {" not in s:
        fail("android/app/build.gradle.kts has no top-level android { block; update tool/prepare_platforms.py")
    s = KEYSTORE_IMPORTS + s
    s = s.replace("\nandroid {", "\n" + KEYSTORE_LOAD + "android {", 1)
    s = s.replace("    buildTypes {", SIGNING_BLOCK + "    buildTypes {", 1)
    s = s.replace('signingConfig = signingConfigs.getByName("debug")',
                  'signingConfig = if (keystorePropertiesFile.exists()) signingConfigs.getByName("release") else signingConfigs.getByName("debug")', 1)
    path.write_text(s, encoding="utf-8")


def patch_plist(path: Path, app_name: str) -> None:
    with path.open("rb") as f:
        data = plistlib.load(f)
    data["CFBundleDisplayName"] = app_name
    data["CFBundleName"] = app_name
    data["ITSAppUsesNonExemptEncryption"] = False  # the app only uses standard HTTPS
    with path.open("wb") as f:
        plistlib.dump(data, f)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--app-id", default="com.tvv.school", help="Android applicationId / iOS bundle id (cannot be changed after publishing)")
    ap.add_argument("--app-name", default="Tufanganj Vivekanand Vidyalaya (H.S.)", help="Name shown under the app icon")
    ap.add_argument("--scaffold-from", help="use an existing scaffold instead of running flutter create (testing)")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        if args.scaffold_from:
            src = Path(args.scaffold_from)
        else:
            src = Path(tmp) / "scaffold"
            scaffold(args.app_id, src)
        for name in ("android", "ios"):
            if not (src / name).is_dir():
                fail(f"scaffold has no {name}/ folder")
            dest = ROOT / name
            if dest.exists():
                shutil.rmtree(dest)
            shutil.copytree(src / name, dest)

    patch_manifest(ROOT / "android/app/src/main/AndroidManifest.xml", args.app_name)
    patch_gradle(ROOT / "android/app/build.gradle.kts")
    patch_plist(ROOT / "ios/Runner/Info.plist", args.app_name)
    print(f"Platforms ready: {args.app_id} / {args.app_name}")


if __name__ == "__main__":
    main()
